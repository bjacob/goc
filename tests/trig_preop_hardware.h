inline uint32_t trig_preop_mode(unsigned m) {
  return (m & 1 ? GOC_ALU_ABS_A : 0) | (m & 2 ? GOC_ALU_NEG_A : 0) | (((m >> 2) & 3) << 6) |
         (m & 16 ? GOC_ALU_CLAMP : 0);
}

