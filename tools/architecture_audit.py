#!/usr/bin/env python3
"""Inventory architecture-sensitive rocjitsu execution policies for GoC review.

Usage: python3 tools/architecture_audit.py /path/to/rocjitsu
This is a review queue, not a semantic-equivalence verifier or a call-graph audit.
"""
import argparse
from collections import defaultdict
import hashlib
from pathlib import Path
import re


def execution_functions(source):
    # Ignore braces inside comments and strings, retaining offsets for line links.
    ignored = r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\''
    code = re.sub(ignored, lambda m: ''.join('\n' if c == '\n' else ' ' for c in m[0]),
                  source, flags=re.S)
    for match in re.finditer(r'\binline\s+void\s+(execute_\w+)\s*\(', code):
        start = code.index('{', match.end())
        depth = 1
        end = start + 1
        while depth and end < len(code):
            depth += (code[end] == '{') - (code[end] == '}')
            end += 1
        if depth:
            raise ValueError(f'Unclosed execution helper: {match[1]}')
        yield match[1], code[start:end], source.count('\n', 0, match.start()) + 1


def read_scope(inventory):
    rows = []
    for line in inventory.splitlines():
        cells = [c.strip() for c in line.split('|')]
        if len(cells) == 9 and cells[1].startswith('`') and cells[4].startswith('in'):
            rows.append((cells[1].strip('`'), cells[2] == 'yes', cells[3] == 'yes'))
    if not rows:
        raise ValueError('No in-scope instruction rows found; regenerate ISA_INVENTORY.md')
    return rows


def direct_policies(body):
    patterns = {
        'OMOD': r'fp_mode::effective_(?:f16_)?omod\s*\(',
        'NaN quieting': r'fp_mode::quiets_nan\s*\(',
        'IEEE mode': r'\bieee_mode\s*\(',
        'architecture query': r'\.arch\s*\(',
        'architecture model': r'\b(?:\w*gfx1[12]\w*|\w*rdna[34]\w*)\b',
        'output helper': r'\bsdwa::write_lane\b',
        'SIMD macro': r'\bROCJITSU_TRY_SIMD_\w+',
    }
    return {label for label, pattern in patterns.items() if re.search(pattern, body)}


def generate(root, rocjitsu):
    scope = read_scope((root / 'ISA_INVENTORY.md').read_text())
    shared = rocjitsu / 'lib/rocjitsu/src/rocjitsu/isa/arch/amdgpu/generated/shared/execute_shared.h'
    source = shared.read_text()
    policies = defaultdict(set)
    locations = defaultdict(list)
    # Longest mnemonic first prevents v_add_f32 from swallowing a longer name.
    names = sorted((n for n, _, _ in scope), key=len, reverse=True)
    for helper, body, line in execution_functions(source):
        stem = helper.removeprefix('execute_')
        name = next((n for n in names if stem == n or stem.startswith(n + '_')), None)
        if name is not None:
            policies[name].update(direct_policies(body))
            locations[name].append((helper, line))
    header = (root / 'include/goc/detail/goc_instructions.h').read_text()
    apis = set(re.findall(r'int goc_(\w+)\(', header))
    common = [(n, a, b) for n, a, b in scope if a and b]
    direct = {'OMOD', 'NaN quieting', 'IEEE mode', 'architecture query', 'architecture model'}
    affected = [n for n, _, _ in common if policies[n] & direct]
    text = f'''# Cross-architecture semantic review queue

Generated by `tools/architecture_audit.py` from the in-scope ISA inventory and
rocjitsu's generated shared execution helpers. This queue covers all
{len(common)} canonical mnemonics present in both architectures, plus counts
{len(scope) - len(common)} architecture-exclusive in-scope mnemonics separately.
It does not infer that identical helper names imply identical semantics.

Source SHA-256 (`execute_shared.h`): `{hashlib.sha256(source.encode()).hexdigest()}`.

## Confirmed cross-cutting differences

- RDNA3 ISA section 7.2.3.1 disables OMOD when output denormals are enabled or
  MODE.IEEE is set. RDNA4's corresponding section and rocjitsu's
  `fp_mode::effective_omod` permit OMOD independently of those settings.
  For example, a finite `v_add_f32` result of 3 with OMOD multiply-by-two is
  3 on RDNA3 when output denormals are enabled, versus 6 on RDNA4. This is a
  specification-derived counterexample, not a new native RDNA3 capture.
- Rocjitsu's `fp_mode::quiets_nan` distinguishes RDNA3's MODE.IEEE setting
  from RDNA4's unconditional quieting. Its conversion, reciprocal and FMA
  paths use this policy. Exact preservation of signaling bits requires a
  per-instruction review; host arithmetic cannot substitute for that review.
- Packed FP16 results ignore OMOD on both architectures. Do not blindly split
  every instruction whose helper mentions the common modifier machinery.
- RDNA3 arithmetic exceptions accumulate in TRAPSTS.EXCP; RDNA4 uses
  EXCP_FLAG_USER. Their low seven arithmetic bits agree, but other fields do not.
  The [register-output naming audit](GLOBAL_STATE_AUDIT.md) tracks resolved names
  separately from pending shared APIs and from reporting accuracy.
- HWREG IDs, writable fields and privilege differ. RDNA4 SETREG pseudocode
  explicitly shifts the write mask by the field offset; RDNA3's printed
  pseudocode omits that shift. The general field-write description and rocjitsu
  support shifted insertion, so the omission is not evidence of a GPU difference.

GoC now separates ordinary FP16/FP32 ADD/SUB/SUBREV/MUL and FP64 ADD/MUL/FMA
into unsuffixed RDNA3 and `_rdna4` APIs, with guest IEEE/denormal flags and scalar/SIMD OMOD-policy tests in both
wave sizes. They remain loose-only: this does not establish exact NaN behavior,
rounding modes or exception reporting. Other RDNA4-based floating APIs must not
be advertised as complete RDNA3 implementations merely because mnemonics match.
Preserve established tests under `_rdna4` when splitting other families and
implement their RDNA3 policy and appropriate guest-state flags explicitly.
The shared helpers identify candidates, not a mechanically safe renaming set.

## Review coverage and limitations

{len(affected)} common mnemonics have direct architecture/IEEE/OMOD/NaN policy
references in at least one matched execution helper. All other common mnemonics
remain listed below. The scan does not traverse calls, macros, output helpers,
SIMD helpers, operand readers, format descriptors or implicit VM state. It also
cannot prove an architecture-specific override delegates to the matched shared
helper. A missing helper is an audit gap, not evidence of compatibility.

`output helper` and `SIMD macro` flag transitive review boundaries. Both scalar
and SIMD implementations, instruction modifiers, wave widths and implicit state
must be reviewed before closing an instruction. The existing API inventory,
hardware captures and test suite are independent evidence, not replacements.

| Mnemonic | Direct policy / review boundaries | Existing RDNA4 split | Shared-helper lines | Status |
|---|---|---|---|---|
'''
    for name, _, _ in common:
        tags = ', '.join(sorted(policies[name])) or 'no direct policy detected'
        split = 'yes' if name + '_rdna4' in apis else 'no'
        lines = ', '.join(str(line) for _, line in locations[name]) or 'not found'
        text += f'| `{name}` | {tags} | {split} | {lines} | review required |\n'
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('rocjitsu', type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    report = generate(root, args.rocjitsu)
    (root / 'ARCHITECTURE_AUDIT.md').write_text(report)
    print('\n'.join(report.splitlines()[:9]))


if __name__ == '__main__':
    main()
