#!/usr/bin/env python3
"""Audit names of existing exception outputs against resolved API architectures.

This does not infer which instructions should have an output, or prove reporting
accuracy. Shared APIs without an architecture split remain a review queue.
"""
import re
import sys
from collections import Counter
from pathlib import Path

sys.dont_write_bytecode = True
from architecture_audit import read_scope


def declarations(header):
    return dict(re.findall(r'int goc_(\w+)\(([^;]*)\);', header))


def reporting_rows(header, inventory):
    apis = declarations(header)
    scope = {name: (rdna3, rdna4) for name, rdna3, rdna4 in read_scope(inventory)}
    rows = []
    for name, parameters in sorted(apis.items()):
        outputs = [match[1] for parameter in parameters.split(',')
                   if (match := re.fullmatch(r'uint32_t\s*\*\s*(excp_flag_user|trapsts)',
                                             parameter.strip()))]
        if not outputs:
            continue
        base = name.removesuffix('_wave64')
        a, b = scope.get(base, (False, False))
        if base.endswith('_rdna4'):
            arch = 'RDNA4' if scope.get(base.removesuffix('_rdna4'), (False, False))[1] else 'unresolved'
        elif a and (not b or base + '_rdna4' in apis):
            arch = 'RDNA3'
        elif b and not a:
            arch = 'RDNA4'
        else:
            arch = 'unresolved'
        expected = {'RDNA3': 'trapsts', 'RDNA4': 'excp_flag_user'}.get(arch)
        status = 'review required' if expected is None else (
            'name matches' if outputs == [expected] else 'name mismatch')
        rows.append((name, arch, ', '.join(outputs), status))
    return rows


def generate(root):
    rows = reporting_rows((root / 'include/goc/detail/goc_instructions.h').read_text(),
                          (root / 'ISA_INVENTORY.md').read_text())
    counts = Counter(row[3] for row in rows)
    text = f'''# Architectural exception-output naming audit

Generated by `python3 tools/global_state_audit.py` from public declarations and
`ISA_INVENTORY.md`. This audits {len(rows)} existing exception-output signatures:
{counts['name matches']} match their resolved architecture's register name,
{counts['name mismatch']} mismatch, and {counts['review required']} require review.

RDNA3 ISA section 3.4 describes wave-wide sticky `TRAPSTS.EXCP`; arithmetic
exceptions occupy bits 0–6. RDNA4 exposes these arithmetic bits in
`EXCP_FLAG_USER`. Rocjitsu's `gfx12_excp_flag_user_raw` maps the same seven low
bits out of its internal TRAPSTS storage. Matching those bits does not make the
architectural registers identical: address-watch, memory and other fields differ.

An unsuffixed API is resolved to RDNA3 when its canonical instruction is RDNA3-only
or when the API has an explicit `_rdna4` counterpart. RDNA4-only instructions and
explicit `_rdna4` APIs resolve to RDNA4. Other shared/unknown names remain pending;
this table does not silently label their existing RDNA4 implementation as shared.

**Limitations:** matching a parameter name does not prove numeric compatibility,
correct reporting, presence/absence of a required register output, or completeness
of the set of writable registers. Pending shared APIs need instruction-level
review and an architecture split where required. Existing non-null exact requests
must still fail explicitly if faithful reporting is unavailable. Loose paths may
skip reporting. This audit neither adds reporting work nor certifies completion.

| API | Resolved target | Existing output | Naming status |
|---|---|---|---|
'''
    text += ''.join(f'| `goc_{name}` | {arch} | `{output}` | {status} |\n'
                    for name, arch, output, status in rows)
    return text


if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    report = generate(root)
    (root / 'GLOBAL_STATE_AUDIT.md').write_text(report)
    print('\n'.join(report.splitlines()[:6]))
